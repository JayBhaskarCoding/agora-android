/**
 * 🌟 The ONE fullscreen media viewer dialog — verbatim behavior of the feed's
 * expanded viewer, now shared by the feed, profile and edit-post screens:
 * pinch-to-zoom images (1–5x, clamped pan) and the ExpandedVideoScreen player
 * for videos. Takes a plain remote URL string, routed through the app-wide
 * isFeedVideoUrl sniffing, so callers never juggle Uri/URL conversions.
 */
@Composable
fun FullscreenMediaViewerDialog(
    mediaUrl: String,
    onDismiss: () -> Unit
) {
    val isVideo = isFeedVideoUrl(mediaUrl)

    Dialog(
        onDismissRequest = onDismiss,
        properties = DialogProperties(
            usePlatformDefaultWidth = false,
            decorFitsSystemWindows = false
        )
    ) {
        if (isVideo) {
            ExpandedVideoScreen(
                videoUrl = mediaUrl,
                onNavigateBack = onDismiss
            )
        } else {
            var scale by remember { mutableFloatStateOf(1f) }
            var offset by remember { mutableStateOf(Offset.Zero) }

            Box(
                modifier = Modifier
                    .fillMaxSize()
                    .background(Color.Black),
                contentAlignment = Alignment.Center
            ) {
                AsyncImage(
                    model = mediaUrl,
                    contentDescription = "Expanded Image",
                    modifier = Modifier
                        .fillMaxSize()
                        .pointerInput(Unit) {
                            detectTransformGestures { _, pan, zoom, _ ->
                                scale = (scale * zoom).coerceIn(1f, 5f)
                                if (scale > 1f) {
                                    val maxX = (size.width * (scale - 1)) / 2
                                    val maxY = (size.height * (scale - 1)) / 2
                                    offset = Offset(
                                        x = (offset.x + pan.x * scale).coerceIn(-maxX, maxX),
                                        y = (offset.y + pan.y * scale).coerceIn(-maxY, maxY)
                                    )
                                } else {
                                    offset = Offset.Zero
                                }
                            }
                        }
                        .graphicsLayer(
                            scaleX = scale,
                            scaleY = scale,
                            translationX = offset.x,
                            translationY = offset.y
                        ),
                    contentScale = ContentScale.Fit
                )

                Box(
                    modifier = Modifier
                        .align(Alignment.TopEnd)
                        .statusBarsPadding()
                        .padding(16.dp)
                        .size(40.dp)
                        .clip(CircleShape)
                        .background(Color.Black.copy(alpha = 0.55f))
                        .border(1.dp, Color.White.copy(alpha = 0.18f), CircleShape)
                        .clickable {
                            onDismiss()
                            scale = 1f
                            offset = Offset.Zero
                        },
                    contentAlignment = Alignment.Center
                ) {
                    Icon(
                        Icons.Default.Close,
                        contentDescription = "Close",
                        tint = Color.White,
                        modifier = Modifier.size(20.dp)
                    )
                }
            }
        }
    }
}
